export function readConfig(env = process.env) {
  const pollIntervalMs = Math.max(5_000, Number(env.POLL_INTERVAL_MS) || 30_000);
  const staleAfterMs = Math.max(pollIntervalMs, Number(env.STALE_AFTER_MS) || 120_000);
  return {
    host: env.API_HOST || '127.0.0.1',
    port: Number(env.API_PORT) || 4000,
    webOrigin: env.WEB_ORIGIN || 'http://127.0.0.1:3001',
    pollIntervalMs,
    staleAfterMs,
    allowHttpSourceDev: env.NODE_ENV !== 'production' && env.ALLOW_HTTP_SOURCE_DEV === 'true',
    databaseUrl: env.DATABASE_URL || '',
    databasePoolMax: Math.min(Math.max(Number(env.PG_POOL_MAX) || 10, 1), 50),
    databaseSsl: env.PG_SSL === 'true',
    databaseSslCaPath: env.PG_SSL_CA_PATH || '',
    oracleSource: {
      enabled: env.ORACLE_SOURCE_ENABLED === 'true',
      connectString: env.ORACLE_SOURCE_CONNECT_STRING || '',
      username: env.ORACLE_SOURCE_USER || '',
      password: env.ORACLE_SOURCE_PASSWORD || '',
      viewName: env.ORACLE_SOURCE_VIEW || 'MONITORING_SOURCE_SUMMARY_V',
      sourceIds: (env.ORACLE_SOURCE_IDS || '').split(',').map((id) => id.trim()).filter(Boolean),
    },
    webhookMaxClockSkewMs: 5 * 60_000,
    webhookCredentials: Object.fromEntries([
      ['inventory_aset', env.WEBHOOK_KEY_ID_INVENTORY_ASET, env.WEBHOOK_SECRET_INVENTORY_ASET],
      ['mitra_pks', env.WEBHOOK_KEY_ID_MITRA_PKS, env.WEBHOOK_SECRET_MITRA_PKS],
      ['app_mobile', env.WEBHOOK_KEY_ID_APP_MOBILE, env.WEBHOOK_SECRET_APP_MOBILE],
      ['antrian_umum', env.WEBHOOK_KEY_ID_ANTRIAN_UMUM, env.WEBHOOK_SECRET_ANTRIAN_UMUM],
      ['antrian_ptsp', env.WEBHOOK_KEY_ID_ANTRIAN_PTSP, env.WEBHOOK_SECRET_ANTRIAN_PTSP],
    ].filter(([, keyId, secret]) => Boolean(keyId && secret)).map(([source, keyId, secret]) => [source, { keyId, secret }])),
    cookieSecure: env.COOKIE_SECURE === 'true' || env.NODE_ENV === 'production',
    sources: sources.map((source) => ({
      ...source,
      url: env[source.urlEnv] || '',
      token: env[source.tokenEnv] || '',
      healthUrl: source.healthEnv ? env[source.healthEnv] || '' : '',
    })),
  };
}
